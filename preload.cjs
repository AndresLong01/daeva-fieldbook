const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('desktop', {
  updateGet: () => ipcRenderer.invoke('update-get'),
  updateCheck: () => ipcRenderer.invoke('update-check'),
  updateDownload: () => ipcRenderer.invoke('update-download'),
  onUpdateState: callback => ipcRenderer.on('update-state', (_event, state) => callback(state)),
  bossFeed: () => ipcRenderer.invoke('boss-feed'),
  goalGet: () => ipcRenderer.invoke('goal-get'),
  goalVariantsGet: () => ipcRenderer.invoke('goal-variants-get'),
  goalSet: goal => ipcRenderer.invoke('goal-set', goal),
  goalAdjust: (itemId, amount) => ipcRenderer.invoke('goal-adjust', itemId, amount),
  goalRemove: itemId => ipcRenderer.invoke('goal-remove', itemId),
  goalSelect: itemId => ipcRenderer.invoke('goal-select', itemId),
  onGoal: callback => ipcRenderer.on('goal-state', (_event, goal) => callback(goal)),
  goalCaptureStatus: () => ipcRenderer.invoke('goal-capture-status-get'),
  onGoalCaptureStatus: callback => ipcRenderer.on('goal-capture-status', (_event, status) => callback(status)),
  timerPinsGet: () => ipcRenderer.invoke('timer-pins-get'),
  timerPinsSet: pins => ipcRenderer.invoke('timer-pins-set', pins),
  timerSeparateGet: () => ipcRenderer.invoke('timer-separate-get'),
  timerSeparateSet: value => ipcRenderer.invoke('timer-separate-set', value),
  timerOverlaySnapshot: snapshot => ipcRenderer.send('timer-overlay-snapshot', snapshot),
  onTimerOverlaySnapshot: callback => ipcRenderer.on('timer-overlay-snapshot', (_event, snapshot) => callback(snapshot)),
  timerAlertToggle: key => ipcRenderer.invoke('timer-alert-toggle', key),
  onTimerAlertPins: callback => ipcRenderer.on('timer-alert-pins', (_event, pins) => callback(pins)),
  onAlertPlay: callback => ipcRenderer.on('alert-play', (_event, volume) => callback(volume)),
  noteOverlaySnapshot: snapshot => ipcRenderer.send('note-overlay-snapshot', snapshot),
  onNoteOverlaySnapshot: callback => ipcRenderer.on('note-overlay-snapshot', (_event, snapshot) => callback(snapshot)),
  overlayResize: dimensions => ipcRenderer.send('overlay-resize', dimensions),
  overlayLockGet: () => ipcRenderer.invoke('overlay-lock-get'),
  overlayLockToggle: () => ipcRenderer.invoke('overlay-lock-toggle'),
  overlayLockButtonBounds: rect => ipcRenderer.send('overlay-lock-button-bounds', rect),
  onOverlayLock: callback => ipcRenderer.on('overlay-lock-state', (_event, locked) => callback(locked)),
  overlayLockClear: () => ipcRenderer.invoke('overlay-lock-clear'),
  overlayContentMin: height => ipcRenderer.send('overlay-content-min', height),
  overlayAppearanceGet: () => ipcRenderer.invoke('overlay-appearance-get'),
  onOverlayAppearance: callback => ipcRenderer.on('overlay-appearance', (_event, appearance) => callback(appearance)),
  themeSet: colors => ipcRenderer.invoke('theme-set', colors),
  onThemeColors: callback => ipcRenderer.on('theme-colors', (_event, colors) => callback(colors)),
  settingsGet: () => ipcRenderer.invoke('settings-get'),
  settingsSet: settings => ipcRenderer.invoke('settings-set', settings),
  overlayVisibilitySet: visible => ipcRenderer.invoke('overlay-visibility-set', visible),
  onOverlayVisibility: callback => ipcRenderer.on('overlay-visibility', (_event, visible) => callback(visible)),
  alertTest: () => ipcRenderer.invoke('alert-test')
});
